"""Render the imported grade-review introduction without changing frozen runs."""

from html import escape


LEGACY_INTRO = (
    "Привет! Мы тут решили заглянуть вглубь наших суперсил и запускаем опрос по компетенциям. "
    "Внутри тебя ждут небольшие закрытые вопросы. Логика простая: выбирай тот вариант, который точнее всего описывает коллегу. "
    "Если по какому-то пункту вы совсем не пересекались в работе — не страшно, этот вопрос можно со спокойной душой скипнуть. "
    "А на десерт в самом конце мы оставили 3 уютных открытых вопроса. "
    "Мы ценим твое время, поэтому сразу сориентируем: опрос займет около 20–25 минут"
)

CHOICE_INSTRUCTION = "Выбирай вариант, который лучше всего описывает работу коллеги."

INTRO = (
    "Привет! 👋🏼\n"
    "Мы тут решили заглянуть вглубь наших суперсил и запускаем опрос по компетенциям. "
    "Внутри тебя ждут небольшие закрытые вопросы."
    "{open_questions}\n\n"
    "📝 **Как проходить опрос:**\n"
    f"{CHOICE_INSTRUCTION}\n"
    "Если по какому-то пункту вы совсем не пересекались в работе — не страшно, этот вопрос можно со спокойной душой скипнуть.\n\n"
    "⏳ Мы ценим твое время, поэтому сразу сориентируем: опрос займет около 20–25 минут"
)


def review_intro(text: str, question_count: int) -> str:
    if text.strip() == LEGACY_INTRO:
        open_questions = " А на десерт в самом конце мы оставили 3 уютных открытых вопроса🤗" if question_count == 3 else (
            " В конце будут открытые вопросы." if question_count else ""
        )
        text = INTRO.format(open_questions=open_questions)
    for placeholder in ("[ИМЯ]", "{name}", "{employee_full_name}"):
        text = text.replace(
            f"Логика простая: выбирай тот вариант, который точнее всего описывает {placeholder}.",
            CHOICE_INSTRUCTION,
        )
    return (escape(text).replace("[ИМЯ]", "{name}")
            .replace("**Как проходить опрос:**", "<b>Как проходить опрос:</b>"))
