/**
 * Словарь проверок интерфейса. Слой, который почти не меняется.
 *
 * Инструмент разработки: приложением не раздаётся, в сборку не попадает.
 * Выполняется в браузере на открытой странице админки — содержимое файла
 * передаётся на выполнение в открытой вкладке. Заводит window.UIChecks
 * и живёт до следующего перехода по адресу.
 *
 * Здесь описаны виды проблем, а не конкретные элементы: «не прыгает»,
 * «на одной оси», «контраст не ниже». Поэтому проверки годятся для любого
 * блока — сайдбара, карточки, таблицы. Что именно проверяем, лежит
 * в suites/ отдельными наборами.
 *
 * Внутрь зашиты осторожности, на которых легко обжечься и которые дорого
 * обошлись при разработке сайдбара:
 *
 *   - замер на скрытой странице возвращает устаревшие числа, а не ошибку;
 *   - замер во время перехода читает начало анимации, а не результат;
 *   - контраст зависит от фактического фона и от прозрачности.
 *
 * Один раз записаны здесь — больше вспоминать не нужно.
 */
(() => {
  const ДОПУСК_PX = 1;

  /**
   * Скрытая вкладка замораживает пересчёт стилей: getComputedStyle
   * и getBoundingClientRect продолжают отвечать, но устаревшими значениями.
   * Мерить в таком состоянии хуже, чем не мерить вовсе — получаешь
   * правдоподобное число и делаешь на нём вывод.
   */
  function убедитьсяЧтоСтраницаВидима() {
    if (document.visibilityState !== "visible") {
      throw new Error(
        `страница скрыта (visibilityState = ${document.visibilityState}); ` +
          "замеры заморожены, откройте панель браузера",
      );
    }
  }

  /** Самая долгая анимация среди элементов — сколько ждать до замера. */
  function длительностьПереходов(элементы) {
    let макс = 0;
    for (const эл of элементы) {
      const cs = getComputedStyle(эл);
      for (const часть of `${cs.transitionDuration} ${cs.transitionDelay}`.split(/[\s,]+/)) {
        const мс = часть.endsWith("ms")
          ? parseFloat(часть)
          : часть.endsWith("s")
            ? parseFloat(часть) * 1000
            : 0;
        if (Number.isFinite(мс)) макс = Math.max(макс, мс);
      }
    }
    return макс;
  }

  /**
   * Ждать дольше перехода. Прочитанное сразу после изменения — это начало
   * анимации: значение выглядит неизменившимся, и кажется, будто правило
   * не применилось.
   */
  async function дождатьсяПокоя(элементы) {
    const пауза = Math.max(120, длительностьПереходов(элементы) + 80);
    await new Promise((готово) => setTimeout(готово, пауза));
  }

  const все = (селектор) => [...document.querySelectorAll(селектор)];
  const один = (селектор) => {
    const эл = document.querySelector(селектор);
    if (!эл) throw new Error(`не найден элемент ${селектор}`);
    return эл;
  };

  const лево = (эл) => Math.round(эл.getBoundingClientRect().left);
  const верх = (эл) => Math.round(эл.getBoundingClientRect().top);
  const ширина = (эл) => Math.round(эл.getBoundingClientRect().width);
  const высота = (эл) => Math.round(эл.getBoundingClientRect().height);
  const центрX = (эл) => {
    const b = эл.getBoundingClientRect();
    return Math.round(b.left + b.width / 2);
  };
  const центрY = (эл) => {
    const b = эл.getBoundingClientRect();
    return Math.round(b.top + b.height / 2);
  };

  /* --- геометрия ---------------------------------------------------- */

  /** Элементы не должны сдвигаться при переключении состояния. */
  async function неПрыгает(селектор, переключить, ось = лево) {
    const до = все(селектор).map(ось);
    await переключить();
    await дождатьсяПокоя(все(селектор));
    const после = все(селектор).map(ось);
    await переключить();
    await дождатьсяПокоя(все(селектор));
    const совпало = JSON.stringify(до) === JSON.stringify(после);
    return {
      прошло: совпало,
      подробности: совпало
        ? `${до.length} шт. на ${до[0]}px в обоих состояниях`
        : `было ${JSON.stringify(до)}, стало ${JSON.stringify(после)}`,
    };
  }

  /** Все элементы выровнены по одной линии. */
  function наОднойОси(селектор, ось = лево) {
    const значения = все(селектор).map(ось);
    if (!значения.length) return { прошло: false, подробности: `ничего не найдено по ${селектор}` };
    const разброс = Math.max(...значения) - Math.min(...значения);
    return {
      прошло: разброс <= ДОПУСК_PX,
      подробности: `${значения.length} шт. на ${значения[0]}px, разброс ${разброс}px`,
    };
  }

  /** Центр элемента лежит на заданном крае контейнера. */
  function наГранице(селекторЭлемента, селекторКонтейнера, край = "right") {
    const эл = один(селекторЭлемента);
    const кон = один(селекторКонтейнера);
    const поГоризонтали = край === "right" || край === "left";
    const центр = поГоризонтали ? центрX(эл) : центрY(эл);
    const граница = Math.round(кон.getBoundingClientRect()[край]);
    return {
      прошло: Math.abs(центр - граница) <= ДОПУСК_PX,
      подробности: `центр ${центр}, граница ${граница}`,
    };
  }

  /**
   * Видимые границы элемента по горизонтали.
   *
   * getBoundingClientRect отдаёт геометрию раскладки, а не то, что нарисовано.
   * Предок с overflow: hidden срезает видимую часть, не меняя эту геометрию,
   * поэтому элемент числится на месте, а на экране обрезан. Именно так
   * разделитель полосы заголовка терял по 20px с каждой стороны, а проверка
   * рапортовала «зазор ноль».
   *
   * Поэтому пересекаем прямоугольник элемента со всеми предками, которые
   * режут переполнение.
   */
  function видимыеГраницы(эл) {
    const b = эл.getBoundingClientRect();
    let лево = b.left;
    let право = b.right;
    for (let у = эл.parentElement; у && у.nodeType === 1; у = у.parentElement) {
      if (getComputedStyle(у).overflowX === "visible") continue;
      const п = у.getBoundingClientRect();
      лево = Math.max(лево, п.left);
      право = Math.min(право, п.right);
    }
    return { лево, право, обрезан: лево > b.left + 0.5 || право < b.right - 0.5 };
  }

  /**
   * Элемент занимает поле по горизонтали от края до края — по видимой части.
   *
   * Сравнивать надо именно с полем контента, а не с собственным контейнером
   * элемента: блочный элемент всегда занимает ширину родителя, поэтому такое
   * сравнение проходит всегда и не проверяет ничего. Поле ограничено сайдбаром
   * и краем экрана, и совпадение с ним разметкой не гарантировано.
   */
  function вСтыкСПолем(селектор, полеСелектор = ".main") {
    const эл = один(селектор);
    const видимо = видимыеГраницы(эл);
    const поле = один(полеСелектор).getBoundingClientRect();
    const слева = Math.round(видимо.лево - поле.left);
    const справа = Math.round(поле.right - видимо.право);
    return {
      прошло: Math.abs(слева) <= ДОПУСК_PX && Math.abs(справа) <= ДОПУСК_PX,
      подробности:
        `зазор слева ${слева}px, справа ${справа}px` +
        (видимо.обрезан ? " (видимая часть обрезана предком с overflow)" : ""),
    };
  }

  /** Два элемента выровнены друг относительно друга. */
  function напротив(селекторA, селекторB, ось = центрY) {
    const a = ось(один(селекторA));
    const b = ось(один(селекторB));
    return { прошло: Math.abs(a - b) <= ДОПУСК_PX, подробности: `${a} и ${b}` };
  }

  /**
   * Элементы внутри общего предка совпадают по замеру.
   *
   * Группировка обязательна: полос на странице несколько, и доли
   * четырёхколоночной не равны долям трёхколоночной. Без группировки проверка
   * сравнивала бы четверти с третями и падала бы на исправной раскладке.
   *
   * По умолчанию группа — прямой родитель, а замер — ширина. Для шапок
   * модулей нужно и другое: они лежат каждая в своей карточке, поэтому
   * группу задают селектором предка, а сравнивают высоты.
   */
  function равныеДоли(селектор, настройки = {}) {
    const мера = настройки.мера || ширина;
    const группаСелектор = настройки.группа;
    const элементы = все(селектор);
    if (!элементы.length) return { прошло: false, подробности: `ничего не найдено по ${селектор}` };

    const поГруппам = new Map();
    for (const эл of элементы) {
      const ключ = группаСелектор ? эл.closest(группаСелектор) : эл.parentElement;
      const группа = поГруппам.get(ключ) || [];
      группа.push(мера(эл));
      поГруппам.set(ключ, группа);
    }

    const значения = [...поГруппам.values()];
    const разброс = (набор) => Math.max(...набор) - Math.min(...набор);
    const худший = Math.max(...значения.map(разброс));
    return {
      прошло: худший <= ДОПУСК_PX,
      подробности:
        `${поГруппам.size} групп, худший разброс ${худший}px` +
        (худший > ДОПУСК_PX ? `: ${JSON.stringify(значения.find((н) => разброс(н) === худший))}` : ""),
    };
  }

  /** Расстояние между соседними элементами. */
  function промежуток(селектор, ожидаемый) {
    const элементы = все(селектор);
    if (элементы.length < 2) return { прошло: false, подробности: "нужно хотя бы два элемента" };
    const зазоры = [];
    for (let i = 1; i < элементы.length; i += 1) {
      зазоры.push(
        Math.round(
          элементы[i].getBoundingClientRect().top - элементы[i - 1].getBoundingClientRect().bottom,
        ),
      );
    }
    const одинаковые = new Set(зазоры).size === 1;
    return {
      прошло: одинаковые && зазоры[0] === ожидаемый,
      подробности: одинаковые ? `${зазоры[0]}px, ожидалось ${ожидаемый}px` : `разные: ${зазоры.join(", ")}`,
    };
  }

  /* --- контраст ----------------------------------------------------- */

  const вЛинейный = (c) => (c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4));
  const яркость = ([r, g, b]) =>
    0.2126 * вЛинейный(r) + 0.7152 * вЛинейный(g) + 0.0722 * вЛинейный(b);

  function разобратьЦвет(строка) {
    const m = String(строка).match(/rgba?\(([^)]+)\)/);
    if (!m) return null;
    const ч = m[1].split(/[\s,/]+/).filter(Boolean).map(Number);
    return { rgb: [ч[0] / 255, ч[1] / 255, ч[2] / 255], alpha: ч.length > 3 ? ч[3] : 1 };
  }

  /**
   * Фактический фон под элементом.
   *
   * Возвращает null, если по пути встретился градиент: свести его к одному
   * числу нельзя, а выдать неверное хуже, чем признаться. Тогда фон
   * передаётся явно параметром.
   */
  function фонПод(эл) {
    for (let у = эл; у && у.nodeType === 1; у = у.parentElement) {
      const cs = getComputedStyle(у);
      if (cs.backgroundImage && cs.backgroundImage !== "none") return null;
      const цвет = разобратьЦвет(cs.backgroundColor);
      if (цвет && цвет.alpha === 1) return цвет.rgb;
    }
    return [1, 1, 1];
  }

  /** Суммарная прозрачность с учётом предков: она гасит контраст. */
  function итоговаяПрозрачность(эл) {
    let a = 1;
    for (let у = эл; у && у.nodeType === 1; у = у.parentElement) {
      a *= parseFloat(getComputedStyle(у).opacity || "1");
    }
    return a;
  }

  /**
   * Порог WCAG: 4.5 для обычного текста, 3 для крупного и для нетекстовых
   * элементов. Токен, выровненный по белому, на фоне посветлее даёт меньше —
   * поэтому фон берётся фактический, а не предполагаемый.
   */
  function контрастНеНиже(селектор, порог, настройки = {}) {
    const эл = один(селектор);
    const явныйФон = настройки.фон ? разобратьЦвет(настройки.фон) : null;
    const фон = явныйФон ? явныйФон.rgb : фонПод(эл);
    if (!фон) {
      return {
        прошло: false,
        подробности: "под элементом градиент — передайте фон явно: { фон: 'rgb(...)' }",
      };
    }
    const текст = разобратьЦвет(getComputedStyle(эл).color);
    const a = итоговаяПрозрачность(эл) * (текст.alpha ?? 1);
    const смешанный = текст.rgb.map((v, i) => v * a + фон[i] * (1 - a));
    const L1 = Math.max(яркость(смешанный), яркость(фон));
    const L2 = Math.min(яркость(смешанный), яркость(фон));
    const отношение = (L1 + 0.05) / (L2 + 0.05);
    return {
      прошло: отношение >= порог,
      подробности:
        `${отношение.toFixed(2)}:1 при пороге ${порог}` +
        (a < 1 ? ` (прозрачность ${a.toFixed(2)})` : ""),
    };
  }

  /* --- доступность и загрузка --------------------------------------- */

  /**
   * Управление, спрятанное до наведения, обязано оставаться достижимым
   * с клавиатуры — иначе им нельзя пользоваться без мыши. Про тач
   * отдельно: там нужен @media (hover: none), это проверяется эмуляцией.
   */
  async function скрытоНоДостижимоСКлавиатуры(селектор) {
    const эл = один(селектор);
    const сначала = parseFloat(getComputedStyle(эл).opacity);
    эл.focus();
    await дождатьсяПокоя([эл]);
    const вФокусе = parseFloat(getComputedStyle(эл).opacity);
    эл.blur();
    await дождатьсяПокоя([эл]);
    return {
      прошло: сначала === 0 && вФокусе === 1,
      подробности: `при загрузке ${сначала}, в фокусе ${вФокусе}`,
    };
  }

  /**
   * Смещение раскладки при загрузке. Состояние, которое восстанавливает JS
   * после монтирования, успевает мигнуть — метрика ловит это числом.
   * Порог «хорошо» по CLS — 0.1.
   */
  async function смещениеПриЗагрузкеНиже(порог) {
    const записи = [];
    const наблюдатель = new PerformanceObserver((список) => {
      for (const з of список.getEntries()) записи.push(з.value);
    });
    наблюдатель.observe({ type: "layout-shift", buffered: true });
    await new Promise((готово) => setTimeout(готово, 300));
    наблюдатель.disconnect();
    const сумма = записи.reduce((a, b) => a + b, 0);
    return {
      прошло: сумма < порог,
      подробности: `${сумма.toFixed(4)} при пороге ${порог} (${записи.length} смещений)`,
    };
  }

  /* --- запуск набора ------------------------------------------------ */

  /**
   * Запуск набора.
   *
   * Каждый элемент набора — это `[имя, проверка]` либо `[имя, проверка, контроль]`.
   *
   * Контроль — вторая функция, которая обязана ту же проверку **провалить**.
   * Он нужен потому, что проверка может быть устроена так, что не провалится
   * никогда. Именно это и случилось: разделитель сравнивался с его собственным
   * контейнером, а блочный элемент всегда занимает ширину родителя — «прошло»
   * означало лишь то, что разметка не сломана.
   *
   * Если контроль проходит, значит проверка не различает случаи, и её результат
   * ничего не стоит. Такая строка помечается как сломанная, а не как успешная.
   */
  async function выполнить(набор) {
    try {
      убедитьсяЧтоСтраницаВидима();
    } catch (ошибка) {
      return `НЕ ЗАПУСКАЛОСЬ: ${ошибка.message}`;
    }

    const строки = [];
    let провалов = 0;
    let сломанных = 0;

    for (const [имя, проверка, контроль] of набор) {
      let итог;
      try {
        итог = await проверка();
      } catch (ошибка) {
        итог = { прошло: false, подробности: `ошибка: ${ошибка.message}` };
      }

      let контрольПрошёл = null;
      if (контроль) {
        try {
          контрольПрошёл = (await контроль()).прошло;
        } catch {
          /* Контроль обязан провалиться — исключение считается провалом. */
          контрольПрошёл = false;
        }
      }

      if (контрольПрошёл === true) {
        сломанных += 1;
        строки.push(
          `⚠ ${имя.padEnd(40)} проверка не различает случаи: контроль тоже прошёл`,
        );
        continue;
      }

      if (!итог.прошло) провалов += 1;
      строки.push(`${итог.прошло ? "✓" : "✗"} ${имя.padEnd(40)} ${итог.подробности}`);
    }

    строки.push("");
    if (сломанных) {
      строки.push(`Сломанных проверок: ${сломанных}. Их результатам верить нельзя.`);
    }
    строки.push(
      провалов === 0 ? "Остальные проверки прошли." : `Провалено: ${провалов} из ${набор.length}.`,
    );
    return строки.join("\n");
  }

  window.UIChecks = {
    выполнить,
    неПрыгает,
    наОднойОси,
    равныеДоли,
    наГранице,
    вСтыкСПолем,
    видимыеГраницы,
    напротив,
    промежуток,
    контрастНеНиже,
    скрытоНоДостижимоСКлавиатуры,
    смещениеПриЗагрузкеНиже,
    дождатьсяПокоя,
    оси: { лево, верх, центрX, центрY },
    меры: { ширина, высота },
  };

  return "UIChecks загружен: " + Object.keys(window.UIChecks).length + " проверок";
})()
