/**
 * Что проверяем у каркаса и сайдбара.
 *
 * Требует загруженного core.js — он заводит window.UIChecks.
 * Каркас одинаков на всех страницах админки, поэтому набор запускается
 * с любой из них.
 *
 * Добавить новый элемент — значит завести соседний файл в suites/
 * и описать в нём десяток строк на тех же проверках. Словарь в core.js
 * при этом не трогается.
 */
(async () => {
  const { выполнить, неПрыгает, наОднойОси, наГранице, напротив, промежуток } = window.UIChecks;
  const { контрастНеНиже, скрытоНоДостижимоСКлавиатуры, смещениеПриЗагрузкеНиже } = window.UIChecks;

  const переключитьСайдбар = async () => {
    document.querySelector(".app-shell-collapse-toggle").click();
  };

  /*
   * Фон задаётся явно: заливка рельса полупрозрачна (альфа 0.94), поэтому
   * автоопределение её пропускает и уходит выше по дереву. Берём фон
   * страницы — он и просвечивает сквозь рельс, так что это и есть
   * фактический фон под текстом.
   */
  const фонСтраницы = getComputedStyle(document.body).backgroundColor;

  return выполнить([
    ["смещение при загрузке", () => смещениеПриЗагрузкеНиже(0.1)],

    [
      "иконки меню не прыгают",
      () => неПрыгает(".app-shell-rail-nav .app-shell-nav-icon", переключитьСайдбар),
    ],
    ["иконки меню на одной оси", () => наОднойОси(".app-shell-rail-nav .app-shell-nav-icon")],
    ["промежуток между пунктами", () => промежуток(".app-shell-rail-nav .app-shell-nav-link", 7)],

    [
      "кнопка на границе рельса",
      () => наГранице(".app-shell-collapse-toggle", ".app-shell-sidebar-rail", "right"),
    ],
    [
      "кнопка напротив первого пункта",
      () => напротив(".app-shell-collapse-toggle", ".app-shell-rail-nav .app-shell-nav-link"),
    ],
    [
      "кнопка скрыта, но доходит Tab",
      () => скрытоНоДостижимоСКлавиатуры(".app-shell-collapse-toggle"),
    ],

    [
      "контраст активного пункта",
      () => контрастНеНиже(".app-shell-nav-link.is-active", 4.5, { фон: фонСтраницы }),
    ],
    [
      "контраст обычного пункта",
      () => контрастНеНиже(".app-shell-nav-link:not(.is-active)", 4.5, { фон: фонСтраницы }),
    ],
    [
      "контраст кнопки выхода",
      () => контрастНеНиже(".app-shell-logout-button", 4.5, { фон: фонСтраницы }),
    ],
  ]);
})()
