/**
 * Что проверяем у раскладки страницы.
 *
 * Требует загруженного core.js — он заводит window.UIChecks.
 * Набор запускается с любой страницы админки.
 *
 * У проверки ширины объявлен отрицательный контроль. Он здесь не формальность:
 * предыдущая версия сравнивала полосу заголовка с её собственным контейнером
 * и потому не могла провалиться никогда — «прошло» означало лишь то, что
 * разметка не сломана. Контроль ловит именно такие проверки.
 *
 * Дефект ширины виден не на всякой ширине окна: предел --admin-page-max-width
 * равен 1820px, и пока окно уже, зазора нет. Прогонять надо и на широком.
 * То же относится к выравниванию имени страницы: ниже примерно 1880px оно
 * совпадает с содержимым при любой разметке, и провалить проверку нечем.
 *
 * Проверки полосы фильтров имеют смысл на странице, где фильтры есть,
 * а проверки полос модулей — там, где есть полосы. На остальных страницах
 * они отмечаются знаком ⚠ — это не поломка набора, а честное сообщение,
 * что здесь проверке нечего различать. Провалом это быть не должно: иначе
 * реальные дефекты утонут среди строк «конструкции на странице нет».
 */
(async () => {
  const { выполнить, вСтыкСПолем, наОднойОси, равныеДоли, напротив, оси, меры, скрытоНоДостижимоСКлавиатуры } =
    window.UIChecks;

  /** Первый блок содержимого — то, по чему выравнивается имя страницы. */
  const первыйБлокСодержимого = ".admin-page-stack > *:first-child, .admin-page-shell > *:first-child";

  /**
   * Проверка, которой на этой странице нечего мерить, не является находкой.
   *
   * Полосы модулей есть на дашборде, полоса фильтров — в списке; набор
   * запускается с любой страницы. Возврат «провалено» там, где конструкции
   * просто нет, обесценивает вывод: реальные дефекты тонут среди ложных
   * провалов. Такая строка проходит, но её контроль проходит тоже, и она
   * честно помечается знаком ⚠ как ничего не различающая здесь.
   */
  function еслиЕсть(селектор, проверка, чегоНет) {
    if (!document.querySelector(селектор)) {
      return { прошло: true, подробности: `на этой странице ${чегоНет}` };
    }
    return проверка();
  }

  /**
   * Блок с текстом, но без единого управления и без вложенных блоков.
   *
   * Так выглядит подпись, лежащая прямо на фоне страницы: она не принадлежит
   * ни одному блоку и обычно пересказывает то, что уже написано на модулях.
   * Список, форма и полоса фильтров под это описание не подходят — в них есть
   * ссылки, кнопки или поля.
   */
  const БЛОКИ = "[data-slot='card'], [data-slot='page-row'], [data-slot='page-filters'], [data-slot='alert']";
  const УПРАВЛЕНИЯ = "button, a, input, select, textarea";

  /*
   * Сам элемент проверяется отдельно от его содержимого: querySelector ищет
   * только среди потомков, и карточка без единой кнопки внутри — например
   * пустая «Библиотека» на странице документов — засчитывалась подписью
   * на фоне. Карточка остаётся карточкой независимо от того, что в ней лежит.
   */
  function прозаическиеБлоки(селекторДетей) {
    return [...document.querySelectorAll(селекторДетей)].filter(
      (эл) =>
        эл.textContent.trim() &&
        !эл.matches(БЛОКИ) &&
        !эл.querySelector(БЛОКИ) &&
        !эл.querySelector(УПРАВЛЕНИЯ),
    );
  }

  const теньЕсть = (значение) => Boolean(значение) && значение !== "none";

  /**
   * Отделение всплывающего слоя от интерфейса под ним.
   *
   * Слой обязан иметь и тень, и рамку: собственного фона не хватает —
   * --popover и --card совпадают в обеих темах, и выпадающий список давал
   * к фону страницы 1.03:1.
   *
   * Замер делается на открытом слое: закрытого в разметке просто нет.
   * Пауза после открытия обязательна — у слоя есть анимация появления,
   * и прочитанное сразу это её начало, а не результат.
   */
  async function отделениеСлоя(селекторТриггера, селекторСлоя) {
    const триггер = document.querySelector(селекторТриггера);
    if (!триггер) return { прошло: true, подробности: `на странице нет ${селекторТриггера}` };

    триггер.click();
    await new Promise((готово) => setTimeout(готово, 450));

    const слой = document.querySelector(селекторСлоя);
    if (!слой) {
      document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
      return { прошло: false, подробности: "слой не открылся — проверять нечего" };
    }

    const cs = getComputedStyle(слой);
    const тень = cs.boxShadow;
    const рамка = Math.round(parseFloat(cs.borderTopWidth) || 0);

    document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
    await new Promise((готово) => setTimeout(готово, 250));

    return {
      прошло: теньЕсть(тень) && рамка >= 1,
      подробности: `тень ${теньЕсть(тень) ? "есть" : "none"}, рамка ${рамка}px`,
    };
  }

  /**
   * Шеврон селекта обязан отзываться на открытие.
   *
   * Сравниваются два замера: до открытия и после. Пауза обязательна —
   * у поворота есть переход, и прочитанное сразу это его начало.
   *
   * Параметр «повернуть» позволяет прогнать ту же механику вхолостую:
   * если не открывать список, трансформ обязан остаться прежним.
   */
  async function шевронПоворачивается(селекторТриггера, повернуть = true) {
    const триггер = document.querySelector(селекторТриггера);
    if (!триггер) return { прошло: true, подробности: `на странице нет ${селекторТриггера}` };

    /*
     * Целимся по слоту, а не по первому svg: в значении селекта может стоять
     * своя иконка, и querySelector("svg") брал именно её — замер показывал
     * «поворота нет» на исправном шевроне.
     */
    const шеврон = триггер.querySelector("[data-slot='select-trigger-icon']");
    if (!шеврон) return { прошло: false, подробности: "у триггера нет шеврона" };

    /*
     * Читаем и transform, и rotate. Tailwind v4 компилирует rotate-180
     * в самостоятельное свойство rotate, а не в матрицу transform — тот
     * так и остаётся none, и проверка по нему одному давала бы ложный
     * провал на работающем повороте.
     */
    const снимок = () => {
      const cs = getComputedStyle(шеврон);
      return `transform: ${cs.transform}, rotate: ${cs.rotate}`;
    };

    const до = снимок();
    if (повернуть) триггер.click();
    await new Promise((готово) => setTimeout(готово, 400));
    const после = снимок();

    if (повернуть) {
      document.dispatchEvent(new KeyboardEvent("keydown", { key: "Escape", bubbles: true }));
      await new Promise((готово) => setTimeout(готово, 250));
    }

    return {
      прошло: после !== до,
      подробности: `было «${до}», стало «${после}»`,
    };
  }

  /** Полоса фильтров обязана быть первой в содержимом, а не лежать где придётся. */
  function фильтрыИдут(номерРебёнка) {
    const полоса = document.querySelector("[data-slot='page-filters']");
    if (!полоса) return { прошло: true, подробности: "на этой странице фильтров нет" };
    const соседи = [...полоса.parentElement.children];
    const место = соседи.indexOf(полоса) + 1;
    return {
      прошло: место === номерРебёнка,
      подробности: `полоса идёт ${место}-й из ${соседи.length}, ожидалось ${номерРебёнка}-й`,
    };
  }

  const полоса = "header";
  /*
   * Контроль: содержимое намеренно уже поля на величину паддинга контейнера.
   * Если проверка признает его «в стык», значит она ничего не различает.
   */
  const контрольныеСелекторы = [".admin-page-stack", ".admin-page-shell", ".react-page"];
  /*
   * Перебор по порядку, а не селектор через запятую: querySelector выбирает
   * первое совпадение в порядке документа, а .react-page — предок остальных
   * и занимает всё поле. Контроль тогда прошёл бы, и проверка была бы
   * ошибочно объявлена сломанной.
   */
  const контрольныйЭлемент =
    контрольныеСелекторы.find((с) => document.querySelector(с)) || контрольныеСелекторы[0];

  return выполнить([
    [
      "полоса заголовка во всю ширину поля",
      () => вСтыкСПолем(полоса),
      () => вСтыкСПолем(контрольныйЭлемент),
    ],

    [
      "содержимое не шире предела",
      () => {
        const стек = document.querySelector(контрольныйЭлемент);
        if (!стек) return { прошло: false, подробности: "контентный блок не найден" };
        const ширина = Math.round(стек.getBoundingClientRect().width);
        const предел = parseInt(
          getComputedStyle(document.documentElement).getPropertyValue("--admin-page-max-width"),
          10,
        );
        return {
          прошло: ширина <= предел + 1,
          подробности: `${ширина}px при пределе ${предел}px`,
        };
      },
    ],

    [
      "заголовок один на странице",
      () => {
        const h1 = [...document.querySelectorAll("h1")];
        return {
          прошло: h1.length === 1,
          подробности: h1.length === 1 ? `«${h1[0].textContent.trim()}»` : `найдено ${h1.length}`,
        };
      },
    ],

    [
      "доли полосы равны",
      () =>
        еслиЕсть(
          "[data-slot='page-row']",
          () => равныеДоли("[data-slot='page-row'] > *"),
          "полос модулей нет",
        ),
      /*
       * Контроль: в полосе фильтров доли заведомо неравны — поиск растянут
       * на свободное место, а селекты и сегменты фиксированы. Если проверка
       * признаёт равными и их, она не различает ширины вообще.
       */
      () =>
        еслиЕсть(
          "[data-slot='page-row']",
          () => равныеДоли("[data-slot='page-filters'] > *"),
          "полос модулей нет",
        ),
    ],

    [
      "шапки модулей полосы на одной высоте",
      () =>
        еслиЕсть(
          "[data-slot='page-row'] [data-slot='card-header']",
          () =>
            равныеДоли("[data-slot='page-row'] [data-slot='card-header']", {
              мера: меры.высота,
              группа: "[data-slot='page-row']",
            }),
          "модулей с шапками нет",
        ),
      /*
       * Контроль: высоты самих полос заведомо разные — полоса стат-плиток
       * ниже полосы модулей втрое. Если проверка признаёт равными и их,
       * она не различает высоты вообще.
       */
      () =>
        еслиЕсть(
          "[data-slot='page-row'] [data-slot='card-header']",
          () =>
            равныеДоли("[data-slot='page-row']", {
              мера: меры.высота,
              группа: ".admin-page-stack",
            }),
          "модулей с шапками нет",
        ),
    ],

    [
      "нет текста на фоне страницы",
      () => {
        const прозаические = прозаическиеБлоки(
          ".admin-page-stack > *, .admin-page-shell > *",
        );
        return {
          прошло: прозаические.length === 0,
          подробности:
            прозаические.length === 0
              ? "подписей вне блоков нет"
              : `найдено ${прозаические.length}: «${прозаические[0].textContent.trim().slice(0, 60)}»`,
        };
      },
      /*
       * Контроль берёт всё поле контента, а не карточки: страница может
       * состоять из полосы фильтров и записей вовсе без карточек — так
       * устроен каталог сценариев. Контроль по карточкам там находил ноль,
       * проходил, и настоящий провал подменялся отметкой «не различает
       * случаи»: подсаженная подпись на фоне не показывалась как дефект.
       * Текстовые листья без управлений есть на любом отрисованном экране.
       */
      () => {
        const внутри = прозаическиеБлоки(".main *");
        return { прошло: внутри.length === 0, подробности: `${внутри.length}` };
      },
    ],

    [
      "нет карточки в карточке",
      /*
       * Витрина каталога кладёт карточки внутрь карточек намеренно: сцена
       * показывает те самые компоненты, о которых рассказывает. Такая
       * вложенность объявлена признаком data-showcase и не считается —
       * иначе проверка кричала бы на каждой странице каталога, и на её крик
       * перестали бы смотреть.
       */
      () => {
        const вложенные = [...document.querySelectorAll("[data-slot='card'] [data-slot='card']")].filter(
          (карточка) => !карточка.closest("[data-showcase]"),
        );
        return {
          прошло: вложенные.length === 0,
          подробности: вложенные.length === 0 ? "вложенных карточек нет" : `найдено ${вложенные.length}`,
        };
      },
      /*
       * Контроль ищет вложенность, которая есть на любом экране админки:
       * навигация лежит внутри каркаса. По шапкам карточек он не годится —
       * на странице без единой карточки их ноль, контроль проходит, и
       * проверка помечается «не различает случаи» вместо честного вывода.
       */
      () => {
        const вКаркасе = document.querySelectorAll(".app-shell .app-shell-rail-nav");
        return { прошло: вКаркасе.length === 0, подробности: `${вКаркасе.length}` };
      },
    ],

    [
      "полоса фильтров идёт первой",
      () => фильтрыИдут(1),
      /*
       * Контроль просит невозможное место: нумерация детей начинается
       * с единицы, нулевым ребёнком не бывает никто. Он доказывает, что
       * проверка действительно читает положение полосы и сравнивает его
       * с ожидаемым, а не возвращает «прошло» при любом аргументе.
       *
       * Контроль «а не второй ли она» здесь не годится, хотя и напрашивается:
       * он становится истинным ровно тогда, когда дефект есть, и настоящий
       * провал подменяется отметкой «проверка не различает случаи».
       */
      () => фильтрыИдут(0),
    ],

    [
      "всплывающий слой отделён от фона",
      () =>
        отделениеСлоя(
          "[data-slot='page-filters-controls'] [data-slot='select-trigger']",
          "[data-slot='select-content']",
        ),
      /*
       * Контроль: тот же замер, но у самого триггера. Он лежит в потоке,
       * тени у него нет и быть не должно. Если проверка признаёт отделённым
       * и его, она не отличает всплывающий слой от обычного элемента.
       */
      () =>
        отделениеСлоя(
          "[data-slot='page-filters-controls'] [data-slot='select-trigger']",
          "[data-slot='page-filters-controls'] [data-slot='select-trigger']",
        ),
    ],

    [
      "шеврон селекта поворачивается",
      () => шевронПоворачивается("[data-slot='page-filters-controls'] [data-slot='select-trigger']"),
      /*
       * Контроль: та же механика, но список не открывается. Трансформ обязан
       * остаться прежним. Если проверка засчитывает поворотом и это, она
       * сравнивает не состояния, а собственный шум.
       */
      () =>
        шевронПоворачивается(
          "[data-slot='page-filters-controls'] [data-slot='select-trigger']",
          false,
        ),
    ],

    [
      "действия карточки достижимы с клавиатуры",
      /*
       * Иконки записи скрыты до наведения. Наведения не бывает ни с
       * клавиатуры, ни на планшете, поэтому скрытое обязано проявляться
       * по фокусу — иначе единственный способ открыть запись недостижим.
       */
      () => {
        /*
         * Берём карточку, которой сейчас не касается курсор. Под курсором
         * иконки видны по наведению, и проверка «скрыто при загрузке»
         * провалилась бы из-за положения мыши, а не из-за разметки.
         * На это уже попались при первом же прогоне.
         */
        const карточки = [...document.querySelectorAll("[data-slot='card']")];
        const свободная = карточки.find((к) => !к.matches(":hover") && к.querySelector("a[href]"));
        if (!свободная) {
          return { прошло: true, подробности: "нет карточки с действиями вне курсора" };
        }
        свободная.setAttribute("data-проверяем", "");
        return скрытоНоДостижимоСКлавиатуры("[data-проверяем] a[href]").finally(() =>
          свободная.removeAttribute("data-проверяем"),
        );
      },
      /*
       * Контроль: то же самое на имени карточки. Оно видно всегда,
       * непрозрачность по фокусу не меняется, и контроль обязан провалиться.
       * Если проходит — проверка не отличает скрытое от видимого.
       */
      () => {
        const имя = document.querySelector("[data-slot='card'] h3");
        if (!имя) return { прошло: false, подробности: "нет имени карточки" };
        имя.setAttribute("tabindex", "-1");
        return скрытоНоДостижимоСКлавиатуры("[data-slot='card'] h3").finally(() =>
          имя.removeAttribute("tabindex"),
        );
      },
    ],

    [
      "имя страницы над содержимым",
      () => напротив("h1", первыйБлокСодержимого, оси.лево),
      /*
       * Контроль: поле шире колонки содержимого на горизонтальный паддинг
       * контейнера, поэтому по краю поля имя не выравнивается никогда.
       */
      () => напротив("h1", ".main", оси.лево),
    ],

    ["иконки меню на одной оси", () => наОднойОси(".app-shell-rail-nav .app-shell-nav-icon")],
  ]);
})()
