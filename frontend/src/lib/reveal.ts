/**
 * Проявление действий записи.
 *
 * В покое действия карточки скрыты, проявляются по наведению на неё и при
 * фокусе внутри неё. Классы вешаются на сами кнопки, а не на их контейнер:
 * контейнер нельзя сфокусировать, и проверка «скрыто, но достижимо
 * с клавиатуры» мерила бы непрозрачность не того элемента — у ссылки она
 * всегда единица.
 *
 * Правило hover:none обязательно: на планшете наведения не бывает, и без него
 * единственный способ открыть запись оказался бы недостижим. Фокус нужен
 * по той же причине для клавиатуры.
 *
 * Групп две, и это не дублирование. Card из кита несёт класс group/card,
 * и у таблицы такой карточкой оказалась вся выдача целиком: наведение
 * на любую строку поднимало иконки сразу у всех девятнадцати. У строки
 * своя группа group/row, поэтому реагирует только та, под которой курсор.
 *
 * Карточка, собранная не из кита, объявляет group/card сама.
 *
 * 200ms — тайминг шторки из кита, самый мягкий из уже применяемых.
 */
const ПРОЯВЛЕНИЕ_ОБЩЕЕ =
  "opacity-0 transition-opacity duration-200 focus-visible:opacity-100 [@media(hover:none)]:opacity-100";

export const ПРОЯВЛЕНИЕ = {
  card: `${ПРОЯВЛЕНИЕ_ОБЩЕЕ} group-focus-within/card:opacity-100 group-hover/card:opacity-100`,
  row: `${ПРОЯВЛЕНИЕ_ОБЩЕЕ} group-focus-within/row:opacity-100 group-hover/row:opacity-100`,
};
